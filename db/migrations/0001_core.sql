-- Core shop data. Conventions: money is integer cents, times are timestamptz (stored UTC),
-- seeded rows have a stable text `code` so config and tests can refer to them by name.
--
-- Two database roles (docs/DECISIONS.md):
--   owner (POSTGRES_USER): runs migrations and the seed; owns every table.
--   brimline_app:          the engine's runtime role; gets only the grants listed below.

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO brimline_app;

CREATE TABLE customers (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code       text NOT NULL UNIQUE,
    name       text NOT NULL,
    email      text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code         text NOT NULL UNIQUE,
    display_name text NOT NULL,
    role         text NOT NULL CHECK (role IN ('staff', 'planner', 'operator', 'customer')),
    customer_id  bigint REFERENCES customers (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    -- Customers always belong to a customer; staff roles never do.
    CONSTRAINT customer_users_have_a_customer CHECK ((role = 'customer') = (customer_id IS NOT NULL))
);

CREATE TABLE materials (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code       text NOT NULL UNIQUE,
    name       text NOT NULL,
    process    text NOT NULL CHECK (process IN ('fdm', 'resin', 'cnc')),
    color      text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- "machines", not "printers": the shop also has a CNC mill.
CREATE TABLE machines (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code       text NOT NULL UNIQUE,
    name       text NOT NULL,
    process    text NOT NULL CHECK (process IN ('fdm', 'resin', 'cnc')),
    build_x_mm integer NOT NULL CHECK (build_x_mm > 0),
    build_y_mm integer NOT NULL CHECK (build_y_mm > 0),
    build_z_mm integer NOT NULL CHECK (build_z_mm > 0),
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE machine_materials (
    machine_id  bigint NOT NULL REFERENCES machines (id),
    material_id bigint NOT NULL REFERENCES materials (id),
    PRIMARY KEY (machine_id, material_id)
);

-- Staffed shop hours, in the shop's time zone (config/shop.toml). Weekday is ISO: 1 = Monday.
CREATE TABLE shifts (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    weekday   smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    starts_at time NOT NULL,
    ends_at   time NOT NULL,
    CHECK (ends_at > starts_at),
    UNIQUE (weekday, starts_at)
);

CREATE TABLE stock (
    material_id bigint PRIMARY KEY REFERENCES materials (id),
    on_hand_g   integer NOT NULL CHECK (on_hand_g >= 0),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE order_number_seq;

CREATE TABLE orders (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_number text NOT NULL UNIQUE DEFAULT ('BL-' || lpad(nextval('order_number_seq')::text, 4, '0')),
    customer_id  bigint NOT NULL REFERENCES customers (id),
    status       text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_production', 'done', 'cancelled')),
    due_date     date NOT NULL,
    rush         boolean NOT NULL DEFAULT false,
    notes        text NOT NULL DEFAULT '',
    created_by   bigint NOT NULL REFERENCES users (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_id_idx ON orders (customer_id);

-- One job per order line. Tasks (the steps of a job) are generated by the scheduler from M3.
CREATE TABLE jobs (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id    bigint NOT NULL REFERENCES orders (id),
    line_no     integer NOT NULL CHECK (line_no > 0),
    part_name   text NOT NULL,
    quantity    integer NOT NULL CHECK (quantity > 0),
    material_id bigint NOT NULL REFERENCES materials (id),
    status      text NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'planned', 'in_progress', 'done', 'failed', 'cancelled')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (order_id, line_no)
);

CREATE TABLE tasks (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    job_id        bigint NOT NULL REFERENCES jobs (id),
    seq           integer NOT NULL CHECK (seq > 0),
    kind          text NOT NULL
                  CHECK (kind IN ('file_prep', 'print', 'machining', 'cool_down', 'post_process', 'quality_check', 'pack')),
    machine_id    bigint REFERENCES machines (id),
    planned_start timestamptz,
    planned_end   timestamptz,
    actual_start  timestamptz,
    actual_end    timestamptz,
    status        text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'planned', 'running', 'done', 'failed')),
    UNIQUE (job_id, seq),
    CHECK (planned_end > planned_start),
    CHECK (actual_end > actual_start)
);

-- Runtime grants: reference data is read-only for the app; order data can be read, added and
-- updated but never deleted (orders are cancelled, not removed).
GRANT SELECT ON customers, users, materials, machines, machine_materials, shifts, stock TO brimline_app;
GRANT SELECT, INSERT, UPDATE ON orders, jobs, tasks TO brimline_app;
GRANT USAGE ON SEQUENCE order_number_seq TO brimline_app;
